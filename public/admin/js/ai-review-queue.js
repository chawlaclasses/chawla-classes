/**
 * public/admin/js/ai-review-queue.js
 *
 * AI Review Queue — a dedicated section for questions the AI generated
 * (Question Bank's `generatedByAI: true`, still in `draft`), separate from
 * general Question Bank browsing:
 *
 *   AI Generate -> AI Review Queue -> Approve / Reject / Edit -> Question Bank
 *
 * Reuses the same underlying question-bank API endpoints and a few
 * questions.js helpers (richEditorHTML, getRichEditorContent,
 * getSubjectOptionsHTML) — it does not duplicate the question data model
 * or the approval state machine, it just gives AI-drafted content its own
 * focused screen instead of mixing it into the full Question Bank list.
 */

let aiQueueQuestions = [];
let aiGenerationHistory = [];
window._aiQueueTab = window._aiQueueTab || 'pending';

async function loadAIReviewQueue() {
    showLoading();
    try {
        // FIX: was hitting the generic Question Bank list
        // (/questions?generatedByAI=true&status=draft&sortBy=newest).
        // Switched to the dedicated /ai-review-queue endpoint
        // (routes/admin/ai-review-queue.js) — same underlying filter, but
        // keeps this screen's data source in sync with the approve/reject
        // endpoints below instead of duplicating the filter logic here.
        const [res, subjectsRes, classesRes] = await Promise.all([
            apiCall('/ai-review-queue'),
            apiCall('/subjects'),
            apiCall('/classes')
        ]);
        aiQueueQuestions = res?.data || [];
        // Shared with questions.js — lets us reuse openQuestionPreview()
        // for the History/Hierarchy tabs directly from this queue.
        allQuestions = aiQueueQuestions;
        window._subjects = subjectsRes?.data || [];
        window._classes = classesRes?.data || [];
        renderAIReviewQueue();
    } catch (error) {
        showError('Failed to load AI Review Queue', error.message);
    }
}

async function switchAIQueueTab(tab) {
    window._aiQueueTab = tab;
    if (tab === 'history' && aiGenerationHistory.length === 0) {
        const res = await apiCall('/ai/generation-history');
        aiGenerationHistory = res?.data || [];
    }
    renderAIReviewQueue();
}

async function openAIBatchQuestions(batchId) {
    const res = await apiCall(`/ai/generation-history/${batchId}`);
    if (!res || !res.success) { showToast('Error', 'Failed to load batch', 'error'); return; }
    aiQueueQuestions = res.data.questions || [];
    allQuestions = aiQueueQuestions;
    window._aiQueueTab = 'pending';
    window._aiCurrentBatch = res.data.batch;
    renderAIReviewQueue();
}

function renderAIReviewQueue() {
    if (window._aiQueueTab === 'history') {
        renderAIGenerationHistory();
        return;
    }
    // Approve/Reject move a question straight into the live Question Bank,
    // so only roles with questions:approve (admin/super_admin) get those
    // controls. A teacher can still see the whole queue for transparency
    // and Edit their own drafts, they just can't self-approve — see the
    // per-row "Waiting for admin approval" badge below instead of buttons.
    const canApprove = hasPermission('questions:approve');
    contentArea.innerHTML = `
        <div class="toolbar">
            <h2>🤖 AI Review Queue <span class="count">(${aiQueueQuestions.length})</span></h2>
            <div style="display:flex;gap:8px;">
                <button class="btn btn-secondary btn-sm" onclick="switchAIQueueTab('history')"><i class="fas fa-history"></i> Generation History</button>
                <button class="btn btn-secondary btn-sm" onclick="loadAIReviewQueue()"><i class="fas fa-sync"></i> Refresh</button>
                ${canApprove && aiQueueQuestions.length > 0 ? `<button class="btn btn-gold btn-sm" onclick="bulkApproveAIQueue()"><i class="fas fa-check-double"></i> Approve All</button>` : ''}
            </div>
        </div>
        ${!canApprove ? `<div style="color:var(--muted);font-size:12px;margin-bottom:10px;"><i class="fas fa-info-circle"></i> You can review and edit these drafts. An admin needs to approve them before they enter the Question Bank.</div>` : ''}
        ${window._aiCurrentBatch ? `<div style="font-size:12px;color:var(--gold);margin-bottom:10px;"><i class="fas fa-box-open"></i> Viewing batch from ${new Date(window._aiCurrentBatch.createdAt).toLocaleString()} · "${escapeHtml(window._aiCurrentBatch.prompt || '')}" &nbsp; <button class="qsearch-clear" style="position:static;" onclick="window._aiCurrentBatch=null;loadAIReviewQueue();">Clear</button></div>` : ''}
        <div style="color:var(--muted);font-size:13px;margin-bottom:14px;">
            Questions generated by AI Tools land here first as drafts. Review, edit if needed, then Approve to send them into the main Question Bank — or Reject to discard them.
        </div>
        ${aiQueueQuestions.length === 0 ? `
            <div class="empty-state">
                <i class="fas fa-robot" style="font-size:32px;color:var(--muted);"></i>
                <p>No AI-generated questions waiting for review.</p>
            </div>
        ` : `
            <div class="table-container">
                <table>
                    <thead>
                        <tr>
                            <th>Question</th>
                            <th>Chapter</th>
                            <th>Difficulty</th>
                            <th>Marks</th>
                            <th>Generated</th>
                            <th>Actions</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${aiQueueQuestions.map(q => `
                            <tr>
                                <td onclick="openQuestionPreview('${q._id}')" style="cursor:pointer;" title="Click to preview">${escapeHtml((q.questionText || '').substring(0, 90))}${(q.questionText || '').length > 90 ? '...' : ''}</td>
                                <td>${escapeHtml(q.chapter || '—')}</td>
                                <td><span class="status-badge">${escapeHtml(q.difficulty || 'medium')}</span></td>
                                <td>${q.marks || 1}</td>
                                <td>${q.createdAt ? new Date(q.createdAt).toLocaleDateString() : ''}</td>
                                <td>
                                    <div style="display:flex;gap:6px;align-items:center;">
                                        ${canApprove ? `<button class="btn btn-success btn-sm" onclick="approveAIQueueQuestion('${q._id}')" title="Approve"><i class="fas fa-check"></i></button>` : ''}
                                        <button class="btn btn-sm" onclick="editAIQueueQuestion('${q._id}')" title="Edit"><i class="fas fa-edit"></i></button>
                                        ${canApprove ? `<button class="btn btn-danger btn-sm" onclick="rejectAIQueueQuestion('${q._id}')" title="Reject"><i class="fas fa-times"></i></button>` : `<span class="status-badge" style="font-size:10px;" title="An admin needs to approve or reject this before it enters the Question Bank">Awaiting admin</span>`}
                                    </div>
                                </td>
                            </tr>
                        `).join('')}
                    </tbody>
                </table>
            </div>
        `}
    `;
}

// Approving from the queue means the admin just reviewed it right here —
// so it chains the two allowed workflow transitions (draft -> review ->
// approved) in one click instead of making them submit-for-review and
// approve as two separate manual steps.
// FIX: these three actions used to hand-roll the approve/reject workflow
// from the frontend — two chained PUT /questions/:id/status calls for
// approve, a plain DELETE /questions/:id for reject. That bypassed
// routes/admin/ai-review-queue.js entirely, which meant no audit log
// entry, no recordQuestionHistory() trail, and no server-side check that
// the question was actually still sitting in the queue (isQueued()).
// Switched to the dedicated /ai-review-queue endpoints so approve/reject
// go through the same validated, audited workflow as everywhere else, and
// "Reject" now archives (recoverable from Question Bank) instead of
// hard-deleting.
async function approveAIQueueQuestion(id) {
    const result = await apiCall(`/ai-review-queue/${id}/approve`, { method: 'POST' });
    if (!result || !result.success) { showToast('Error', result?.message || 'Failed to approve', 'error'); return; }
    showToast('Approved', result.message || 'Question moved to the Question Bank', 'success');
    loadAIReviewQueue();
}

async function bulkApproveAIQueue() {
    if (!confirm(`Approve all ${aiQueueQuestions.length} AI-generated question(s)? They'll move into the main Question Bank as Approved.`)) return;
    const ids = aiQueueQuestions.map(q => q._id);
    const result = await apiCall('/ai-review-queue/bulk-approve', { method: 'POST', body: JSON.stringify({ ids }) });
    if (!result || !result.success) { showToast('Error', result?.message || 'Failed to approve', 'error'); return; }
    showToast('Approved', result.message || 'All queued questions approved', 'success');
    loadAIReviewQueue();
}

async function rejectAIQueueQuestion(id) {
    if (!confirm('Reject this AI-generated question? It will be archived and can be restored from Question Bank later if needed.')) return;
    const result = await apiCall(`/ai-review-queue/${id}/reject`, { method: 'POST' });
    if (!result || !result.success) { showToast('Error', result?.message || 'Failed to reject', 'error'); return; }
    showToast('Rejected', result.message || 'Question moved out of the queue', 'success');
    loadAIReviewQueue();
}

// A scoped-down edit modal (reusing questions.js's rich-editor helpers)
// that refreshes the AI Review Queue on save instead of the full Question
// Bank view — editQuestion() from questions.js calls loadQuestions() on
// save, which would silently swap this section's content out from under
// the admin, so the queue gets its own save handler instead.
function editAIQueueQuestion(id) {
    const question = aiQueueQuestions.find(q => q._id === id);
    if (!question) return;

    showModal('Edit AI-Generated Question', 'Fix anything before approving', `
        <div class="form-group">
            <label>Subject</label>
            <select id="aiqSubject">
                <option value="">Select subject...</option>
                ${getSubjectOptionsHTML(question.subjectId || '')}
            </select>
        </div>
        <div class="form-group">
            <label>Question Text *</label>
            ${richEditorHTML('aiqText', 'Type your question here...', question.questionText || '')}
        </div>
        <div class="form-group">
            <label>Chapter</label>
            <input type="text" id="aiqChapter" value="${escapeHtml(question.chapter || '')}">
        </div>
        <div class="form-group">
            <label>Options (one per line, first is correct)</label>
            <textarea id="aiqOptions" rows="4">${(question.options || []).map(o => escapeHtml(o.text)).join('\n')}</textarea>
        </div>
        <div class="form-group">
            <label>Marks</label>
            <input type="number" id="aiqMarks" value="${question.marks || 1}">
        </div>
        <div class="form-group">
            <label>Difficulty</label>
            <select id="aiqDifficulty">
                <option value="easy" ${question.difficulty === 'easy' ? 'selected' : ''}>Easy</option>
                <option value="medium" ${!question.difficulty || question.difficulty === 'medium' ? 'selected' : ''}>Medium</option>
                <option value="hard" ${question.difficulty === 'hard' ? 'selected' : ''}>Hard</option>
            </select>
        </div>
        <div class="form-group">
            <label>Explanation</label>
            ${richEditorHTML('aiqExplanation', 'Explain the correct answer...', question.explanation || '')}
        </div>
    `, async () => {
        const optionsText = document.getElementById('aiqOptions').value.trim();
        const options = optionsText.split('\n').filter(o => o.trim());
        if (options.length < 2) { showToast('Error', 'At least 2 options required', 'error'); return; }

        const result = await apiCall(`/questions/${id}`, {
            method: 'PUT',
            body: JSON.stringify({
                questionText: getRichEditorContent('aiqText'),
                subjectId: document.getElementById('aiqSubject').value,
                chapter: document.getElementById('aiqChapter').value.trim() || 'Uncategorized',
                options: options.map((text, index) => ({ text: text.trim(), isCorrect: index === 0 })),
                correctAnswer: options[0].trim(),
                explanation: getRichEditorContent('aiqExplanation'),
                marks: parseInt(document.getElementById('aiqMarks').value) || 1,
                difficulty: document.getElementById('aiqDifficulty').value,
            })
        });
        if (!result || !result.success) { showToast('Error', result?.message || 'Failed to save', 'error'); return; }
        showToast('Success', 'Question updated', 'success');
        closeModal();
        loadAIReviewQueue();
    });
}

function renderAIGenerationHistory() {
    contentArea.innerHTML = `
        <div class="toolbar">
            <h2>🤖 AI Generation History <span class="count">(${aiGenerationHistory.length})</span></h2>
            <div style="display:flex;gap:8px;">
                <button class="btn btn-secondary btn-sm" onclick="switchAIQueueTab('pending')"><i class="fas fa-inbox"></i> Back to Review Queue</button>
            </div>
        </div>
        <div style="color:var(--muted);font-size:13px;margin-bottom:14px;">Every past "Generate Questions" batch, and what happened to it since.</div>
        ${aiGenerationHistory.length === 0 ? `
            <div class="empty-state">
                <i class="fas fa-history" style="font-size:32px;color:var(--muted);"></i>
                <p>No AI generation batches yet.</p>
            </div>
        ` : `
            <div class="table-container">
                <table>
                    <thead>
                        <tr>
                            <th>Date</th>
                            <th>Prompt / Chapter</th>
                            <th>Generated</th>
                            <th>Approved</th>
                            <th>Rejected</th>
                            <th>Pending</th>
                            <th>Actions</th>
                        </tr>
                    </thead>
                    <tbody>
                        ${aiGenerationHistory.map(b => `
                            <tr>
                                <td>${b.createdAt ? new Date(b.createdAt).toLocaleString() : ''}</td>
                                <td>${escapeHtml(b.prompt || '')} <span style="color:var(--muted);font-size:11px;">(${escapeHtml(b.difficultyRequested || 'mixed')})</span></td>
                                <td>${b.countGenerated}</td>
                                <td><span class="status-badge status-active">${b.approved}</span></td>
                                <td><span class="status-badge status-inactive">${b.rejected}</span></td>
                                <td><span class="status-badge">${b.pending}</span></td>
                                <td><button class="btn btn-sm" onclick="openAIBatchQuestions('${b._id}')" title="Open this batch"><i class="fas fa-folder-open"></i></button></td>
                            </tr>
                        `).join('')}
                    </tbody>
                </table>
            </div>
        `}
    `;
}

window.loadAIReviewQueue = loadAIReviewQueue;